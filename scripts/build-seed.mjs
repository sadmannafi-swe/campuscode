#!/usr/bin/env node
// Builds supabase/seed.sql from the content modules in supabase/content.
//
// Nothing in the seed's outputs is hand-typed:
//   * every lesson example is compiled (gcc) or interpreted (python3) and its real stdout stored;
//   * every problem test's expected output comes from running `ref_py`, and `ref_c` is compiled
//     and must produce byte-identical (normalised) output, otherwise the build fails.
//
// Usage: npm run seed:build   (requires gcc and python3 locally; the generated seed.sql is committed)

import { execFileSync } from "node:child_process";
import { mkdtempSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { topics, achievements, settings } from "../supabase/content/meta.mjs";
import { problems } from "../supabase/content/problems.mjs";
import { cChapters, cLessons1 } from "../supabase/content/c-course-1.mjs";
import { cLessons2 } from "../supabase/content/c-course-2.mjs";
import { pyChapters, pyLessons } from "../supabase/content/python-course.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const work = mkdtempSync(path.join(tmpdir(), "cc-seed-"));

// ---------------------------------------------------------------- runners
const normalise = (s) => s.replace(/\r\n/g, "\n").split("\n").map((l) => l.replace(/\s+$/, "")).join("\n").replace(/\n+$/, "");

function runC(code, stdin, label) {
  const dir = mkdtempSync(path.join(work, "c-"));
  const src = path.join(dir, "main.c");
  const bin = path.join(dir, "main");
  writeFileSync(src, code);
  try {
    execFileSync("gcc", ["-std=c11", "-O2", "-Wall", "-Wno-unused-result", "-o", bin, src, "-lm"], { stdio: ["ignore", "pipe", "pipe"] });
  } catch (e) {
    throw new Error(`[${label}] C compile failed:\n${e.stderr}`);
  }
  return execFileSync(bin, [], { input: stdin, cwd: dir, timeout: 5000 }).toString();
}

function runPy(code, stdin, label) {
  const dir = mkdtempSync(path.join(work, "py-"));
  const src = path.join(dir, "main.py");
  writeFileSync(src, code);
  try {
    return execFileSync("python3", ["-I", src], { input: stdin, cwd: dir, timeout: 5000 }).toString();
  } catch (e) {
    throw new Error(`[${label}] Python failed:\n${e.stderr}`);
  }
}

// ---------------------------------------------------------------- SQL helpers
const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => (a && a.length ? `array[${a.map(q).join(", ")}]::text[]` : `'{}'::text[]`);
const bool = (b) => (b ? "true" : "false");

const out = [];
const emit = (s) => out.push(s);

emit(`-- =====================================================================
-- CampusCode seed data — GENERATED by scripts/build-seed.mjs. Do not edit by hand.
-- Idempotent: safe to run repeatedly. Official content only; no user accounts.
-- =====================================================================
begin;
`);

// ---------------------------------------------------------------- meta
emit("-- Topics");
for (const t of topics) {
  emit(`insert into public.problem_topics (slug, name_en, name_bn, description_en, description_bn, sort_order)
values (${q(t.slug)}, ${q(t.name_en)}, ${q(t.name_bn)}, ${q(t.description_en)}, ${q(t.description_bn)}, ${t.sort_order})
on conflict (slug) do update set name_en = excluded.name_en, name_bn = excluded.name_bn,
  description_en = excluded.description_en, description_bn = excluded.description_bn, sort_order = excluded.sort_order;`);
}

emit("\n-- Achievements");
for (const a of achievements) {
  emit(`insert into public.achievements (id, title_en, title_bn, description_en, description_bn, icon, metric, threshold, sort_order)
values (${q(a.id)}, ${q(a.title_en)}, ${q(a.title_bn)}, ${q(a.description_en)}, ${q(a.description_bn)}, ${q(a.icon)}, ${q(a.metric)}, ${a.threshold}, ${a.sort_order})
on conflict (id) do update set title_en = excluded.title_en, title_bn = excluded.title_bn, description_en = excluded.description_en,
  description_bn = excluded.description_bn, icon = excluded.icon, metric = excluded.metric, threshold = excluded.threshold, sort_order = excluded.sort_order;`);
}

emit("\n-- Platform settings");
for (const s of settings) {
  emit(`insert into public.platform_settings (key, value, is_public) values (${q(s.key)}, ${q(JSON.stringify(s.value))}::jsonb, ${bool(s.is_public)})
on conflict (key) do nothing;`);
}

// ---------------------------------------------------------------- courses
const courses = [
  {
    slug: "c-programming", language: "c", sort_order: 1, featured: true,
    title_en: "C Programming", title_bn: "C প্রোগ্রামিং",
    description_en: "The primary CampusCode path. From your first printf() to pointers, files and two complete projects — in the original playlist order.",
    description_bn: "CampusCode-এর মূল পথ। প্রথম printf() থেকে Pointer, ফাইল আর দুটি পূর্ণাঙ্গ প্রজেক্ট পর্যন্ত — প্লেলিস্টের মূল ক্রম অনুযায়ী।",
    level_en: "Beginner to intermediate", level_bn: "শুরু থেকে মাঝারি",
    chapters: cChapters, lessons: [...cLessons1, ...cLessons2], lang: "c",
  },
  {
    slug: "python-programming", language: "python", sort_order: 2, featured: false,
    title_en: "Python Programming", title_bn: "Python প্রোগ্রামিং",
    description_en: "A compact course for transferable programming ideas — basics, conditions and loops, lists and strings, and functions.",
    description_bn: "স্থানান্তরযোগ্য প্রোগ্রামিং ধারণার জন্য একটি সংক্ষিপ্ত কোর্স — বেসিক, শর্ত ও লুপ, List ও String, আর Function।",
    level_en: "Beginner", level_bn: "শুরু থেকে",
    chapters: pyChapters, lessons: pyLessons, lang: "python",
  },
];

let exampleCount = 0;
for (const c of courses) {
  emit(`\n-- Course: ${c.slug}`);
  emit(`insert into public.courses (slug, language, title_en, title_bn, description_en, description_bn, level_en, level_bn, sort_order, is_published, is_featured)
values (${q(c.slug)}, ${q(c.language)}, ${q(c.title_en)}, ${q(c.title_bn)}, ${q(c.description_en)}, ${q(c.description_bn)}, ${q(c.level_en)}, ${q(c.level_bn)}, ${c.sort_order}, true, ${bool(c.featured)})
on conflict (slug) do update set title_en = excluded.title_en, title_bn = excluded.title_bn, description_en = excluded.description_en,
  description_bn = excluded.description_bn, level_en = excluded.level_en, level_bn = excluded.level_bn, sort_order = excluded.sort_order;`);

  for (const ch of c.chapters) {
    emit(`insert into public.chapters (course_id, slug, title_en, title_bn, description_en, description_bn, sort_order)
select id, ${q(ch.slug)}, ${q(ch.title_en)}, ${q(ch.title_bn)}, ${q(ch.description_en)}, ${q(ch.description_bn)}, ${ch.sort_order}
from public.courses where slug = ${q(c.slug)}
on conflict (course_id, slug) do update set title_en = excluded.title_en, title_bn = excluded.title_bn,
  description_en = excluded.description_en, description_bn = excluded.description_bn, sort_order = excluded.sort_order;`);
  }

  const seen = new Set();
  for (const l of c.lessons) {
    if (seen.has(l.number)) throw new Error(`Duplicate lesson number ${l.number} in ${c.slug}`);
    seen.add(l.number);
    if (!c.chapters.find((ch) => ch.slug === l.chapter)) throw new Error(`Unknown chapter ${l.chapter}`);
    emit(`insert into public.lessons (course_id, chapter_id, slug, number, title_en, title_bn, summary_en, summary_bn,
  objectives_en, objectives_bn, body_en, body_bn, common_mistakes_en, common_mistakes_bn, practice_en, practice_bn,
  is_project, practice_topic_id, estimated_minutes, is_published)
select c.id, ch.id, ${q(l.slug)}, ${l.number}, ${q(l.title_en)}, ${q(l.title_bn)}, ${q(l.summary_en)}, ${q(l.summary_bn)},
  ${arr(l.objectives_en)}, ${arr(l.objectives_bn)}, ${q(l.body_en)}, ${q(l.body_bn)},
  ${arr(l.mistakes_en)}, ${arr(l.mistakes_bn)}, ${arr(l.practice_en)}, ${arr(l.practice_bn)},
  ${bool(l.is_project)}, ${l.topic ? `(select id from public.problem_topics where slug = ${q(l.topic)})` : "null"}, ${l.minutes}, true
from public.courses c join public.chapters ch on ch.course_id = c.id and ch.slug = ${q(l.chapter)}
where c.slug = ${q(c.slug)}
on conflict (course_id, slug) do update set chapter_id = excluded.chapter_id, number = excluded.number,
  title_en = excluded.title_en, title_bn = excluded.title_bn, summary_en = excluded.summary_en, summary_bn = excluded.summary_bn,
  objectives_en = excluded.objectives_en, objectives_bn = excluded.objectives_bn, body_en = excluded.body_en, body_bn = excluded.body_bn,
  common_mistakes_en = excluded.common_mistakes_en, common_mistakes_bn = excluded.common_mistakes_bn,
  practice_en = excluded.practice_en, practice_bn = excluded.practice_bn, is_project = excluded.is_project,
  practice_topic_id = excluded.practice_topic_id, estimated_minutes = excluded.estimated_minutes;`);

    emit(`delete from public.lesson_examples where lesson_id = (select l.id from public.lessons l join public.courses c on c.id = l.course_id where c.slug = ${q(c.slug)} and l.slug = ${q(l.slug)});`);
    (l.examples || []).forEach((ex, i) => {
      const label = `${c.slug}#${l.number}.${i + 1}`;
      const stdin = ex.stdin || "";
      const output = c.lang === "c" ? runC(ex.code, stdin, label) : runPy(ex.code, stdin, label);
      if (!output.trim()) throw new Error(`[${label}] produced no output`);
      exampleCount++;
      emit(`insert into public.lesson_examples (lesson_id, sort_order, title_en, title_bn, language, code, stdin, expected_output, explanation_en, explanation_bn)
select l.id, ${i}, ${q(ex.title_en)}, ${q(ex.title_bn)}, ${q(c.lang)}, ${q(ex.code)}, ${q(stdin)}, ${q(output.replace(/\s+$/, ""))}, ${q(ex.explanation_en)}, ${q(ex.explanation_bn)}
from public.lessons l join public.courses c on c.id = l.course_id where c.slug = ${q(c.slug)} and l.slug = ${q(l.slug)};`);
    });
  }
}

// ---------------------------------------------------------------- problems
const C_STARTER = `#include <stdio.h>

int main(void) {
    /* Read the input, solve the problem and print the answer. */

    return 0;
}
`;
const PY_STARTER = `# Read the input with input(), solve the problem and print the answer.

`;

let testCount = 0;
emit("\n-- Official problems");
const slugs = new Set();
for (const p of problems) {
  if (slugs.has(p.slug)) throw new Error(`Duplicate problem ${p.slug}`);
  slugs.add(p.slug);
  if (!topics.find((t) => t.slug === p.topic)) throw new Error(`Unknown topic ${p.topic}`);

  const outputs = p.inputs.map((input, i) => {
    const label = `${p.slug} test ${i + 1}`;
    const py = runPy(p.ref_py, input + "\n", label);
    if (p.ref_c) {
      const c = runC(p.ref_c, input + "\n", label);
      if (normalise(c) !== normalise(py)) {
        throw new Error(`[${label}] C and Python reference outputs differ:\nC:  ${JSON.stringify(c)}\nPY: ${JSON.stringify(py)}`);
      }
    }
    return normalise(py);
  });

  emit(`insert into public.problems (slug, title, title_bn, statement, statement_bn, input_format, output_format, constraints, explanation,
  hints, difficulty, topic_id, starter_code_c, starter_code_python, is_official, visibility, status, is_featured)
values (${q(p.slug)}, ${q(p.title)}, ${q(p.title_bn)}, ${q(p.statement)}, ${q(p.statement_bn)}, ${q(p.input_format)}, ${q(p.output_format)},
  ${q(p.constraints)}, ${q(p.explanation)}, ${arr(p.hints)}, ${q(p.difficulty)}, (select id from public.problem_topics where slug = ${q(p.topic)}),
  ${q(p.starter_c || C_STARTER)}, ${q(p.starter_py || PY_STARTER)}, true, 'public', 'published', ${bool(p.featured)})
on conflict (slug) do update set title = excluded.title, title_bn = excluded.title_bn, statement = excluded.statement,
  statement_bn = excluded.statement_bn, input_format = excluded.input_format, output_format = excluded.output_format,
  constraints = excluded.constraints, explanation = excluded.explanation, hints = excluded.hints, difficulty = excluded.difficulty,
  topic_id = excluded.topic_id, starter_code_c = excluded.starter_code_c, starter_code_python = excluded.starter_code_python;`);
  emit(`delete from public.test_cases where problem_id = (select id from public.problems where slug = ${q(p.slug)});`);
  p.inputs.forEach((input, i) => {
    testCount++;
    emit(`insert into public.test_cases (problem_id, sort_order, input, expected_output, is_sample)
select id, ${i}, ${q(input)}, ${q(outputs[i])}, ${bool(i < p.samples)} from public.problems where slug = ${q(p.slug)};`);
  });
}

emit("\ncommit;");
writeFileSync(path.join(root, "supabase", "seed.sql"), out.join("\n") + "\n");
rmSync(work, { recursive: true, force: true });

const lessonCount = courses.reduce((n, c) => n + c.lessons.length, 0);
console.log(`seed.sql written: ${courses.length} courses, ${lessonCount} lessons, ${exampleCount} verified examples, ` +
  `${problems.length} problems, ${testCount} verified tests (C and Python references agree).`);
